class AnnotationStatus(StrEnum):
    """Whether an annotation is current or soft-deleted."""

    ACTIVE = "active"
    DELETED = "deleted"


class AnnotationOrigin(StrEnum):
    """How an annotation entered SAB: created in SAB or imported from GPAD."""

    DIRECT = "direct"
    IMPORT = "import"


class ChangeSource(StrEnum):
    """The workflow recorded on an annotation version.

    Version history uses this to show how each change was made, and annotation
    refreshes use it to tell local edits apart from changes SAB made itself.
    """

    API = "api"
    """A direct create, update, or delete request."""
    CHANGE_SET = "change_set"
    """An accepted change-set proposal."""
    ONTOLOGY_REFRESH = "ontology_refresh"
    """An automatic replacement of an obsolete ontology term."""
    ANNOTATION_REFRESH = "annotation_refresh"
    """An import of a group's annotations from a GPAD source."""
    ANNOTATION_CUTOVER = "annotation_cutover"
    """The final GPAD import made when a group moves to SAB management."""


def new_annotation_id() -> UUID:
    """Generate a unique SAB identifier for an annotation.

    Returns:
        A new UUID generated by SAB.
    """
    return uuid4()


class AnnotationNotFoundError(NotFoundError):
    """Report an annotation that is missing or outside the caller's scope."""

    code = "annotation_not_found"
    message = "Annotation was not found"

    def __init__(self, annotation_id: UUID) -> None:
        self.annotation_id = annotation_id
        super().__init__()


class AnnotationDeletedError(AnnotationNotFoundError):
    """Report an annotation that has been soft-deleted.

    Clients receive the same response as for a missing annotation. The separate
    class lets workflows such as change-set acceptance tell the cases apart.
    """


class AnnotationVersionNotFoundError(NotFoundError):
    """Report a saved version that an existing annotation does not have."""

    code = "version_not_found"
    message = "Annotation version was not found"

    def __init__(self, annotation_id: UUID, version: int) -> None:
        self.annotation_id = annotation_id
        self.version = version
        super().__init__()


class DuplicateAnnotationError(ConflictError):
    """Report that a write would duplicate active annotations."""

    code = "duplicate_annotation"
    message = "Annotation conflicts with active duplicates"

    def __init__(self, peer_ids: Iterable[UUID]) -> None:
        self.peer_ids = tuple(peer_ids)
        super().__init__()

    def details(self) -> ErrorDetails:
        """Return the identifiers of the conflicting annotations."""
        return DuplicatePeers(peer_ids=self.peer_ids)


class StaleAnnotationVersionError(PreconditionFailedError):
    """Report that the annotation changed since the version the client expected."""

    code = "stale_annotation_version"
    message = "Annotation version does not match If-Match"

    def __init__(
        self, annotation_id: UUID, expected_version: int, current_version: int
    ) -> None:
        self.annotation_id = annotation_id
        self.expected_version = expected_version
        self.current_version = current_version
        super().__init__()

    def details(self) -> ErrorDetails:
        """Return the expected and current versions."""
        return StaleVersion(
            annotation_id=self.annotation_id,
            expected_version=self.expected_version,
            current_version=self.current_version,
        )


class InvalidAnnotationPayloadError(InvalidInputError):
    """Report an annotation payload that fails schema validation.

    Issue locations start with `annotation`, because they describe the annotation
    the request would produce rather than one part of the request.
    """

    code = "invalid_annotation"
    message = "Annotation payload is invalid"

    def __init__(self, errors: tuple[ValidationIssue, ...]) -> None:
        self.errors = errors
        super().__init__()

    def details(self) -> ErrorDetails:
        """Return every validation issue."""
        return self.errors


class EmptyAnnotationPatchError(InvalidInputError):
    """Report a patch that names no fields."""

    code = "empty_annotation_patch"
    message = "Annotation patch must include at least one field"

    def issue_location(self) -> tuple[str | int, ...]:
        """Return the request body."""
        return ("body",)
